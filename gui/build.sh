#!/bin/bash
# Builds the daemon CLI and the GUI, stamps both with a date version, and
# leaves a ready-to-run .app in ./output.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# Version is the build date: YY.MM.DD, e.g. 26.08.23. Override with
# VPNKS_VERSION=… to stamp something else.
VERSION="${VPNKS_VERSION:-$(date +%y.%m.%d)}"
# CFBundleVersion must increase monotonically; seconds-into-the-day does
# that for repeated builds on the same date.
BUILD_NUM="$(date +%H%M%S)"
echo "==> Version $VERSION (build $BUILD_NUM)"

# Single source of truth for the daemon's own --version.
cat > "$ROOT/swift/Sources/vpnks/Version.swift" <<SWIFT
// Generated by gui/build.sh — do not edit by hand.
enum Build {
    static let version = "$VERSION"
    static let number  = "$BUILD_NUM"
}
SWIFT

# Regenerate the icon set whenever the vector source changes, so editing
# AppIcon.svg is all that is needed to restyle the app icon.
ICONSET="$ROOT/gui/VPNKillSwitch/Assets.xcassets/AppIcon.appiconset"
if [[ "$ROOT/gui/Icon/AppIcon.svg" -nt "$ICONSET/icon_512x512@2x.png" ]]; then
    echo "==> Rendering app icon from AppIcon.svg"
    swiftc -O "$ROOT/gui/Icon/render.swift" -o /tmp/vpnks-rendericon 2>/dev/null
    /tmp/vpnks-rendericon "$ROOT/gui/Icon/AppIcon.svg" "$ICONSET" | sed 's/^/    /'
fi

echo "==> Building vpnks daemon (release)"
cd "$ROOT/swift"
swift build -c release
CLI="$ROOT/swift/.build/release/vpnks"

echo "==> Building VPN Kill Switch.app (release)"
cd "$ROOT"
xcodebuild -project gui/VPNKillSwitch.xcodeproj \
           -scheme VPNKillSwitch \
           -configuration Release \
           -derivedDataPath gui/.build \
           MARKETING_VERSION="$VERSION" \
           CURRENT_PROJECT_VERSION="$BUILD_NUM" \
           build > /dev/null

APP="$ROOT/gui/.build/Build/Products/Release/VPN Kill Switch.app"
[[ -d "$APP" ]] || { echo "build failed: app not found"; exit 1; }

echo "==> Bundling the daemon inside the app"
cp "$CLI" "$APP/Contents/Resources/vpnks"
chmod +x "$APP/Contents/Resources/vpnks"

# Re-sign ad-hoc: adding a file to the bundle invalidates the signature,
# and macOS refuses to launch an app whose seal is broken.
codesign --force --deep --sign - "$APP" 2>/dev/null

# Stable output location. The Xcode build directory is an implementation
# detail and its name changes with configuration.
OUT="$ROOT/output"
mkdir -p "$OUT"
rm -rf "$OUT/VPN Kill Switch.app"
ditto "$APP" "$OUT/VPN Kill Switch.app"
cp "$CLI" "$OUT/vpnks"

# macOS caches app icons by bundle path; nudge LaunchServices so a changed
# icon shows up in the Dock and Finder straight away.
touch "$OUT/VPN Kill Switch.app"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister \
    -f "$OUT/VPN Kill Switch.app" >/dev/null 2>&1 || true

echo
echo "Output:  $OUT/VPN Kill Switch.app   (v$VERSION)"
echo "         $OUT/vpnks                 (daemon CLI)"
echo "Run:     open '$OUT/VPN Kill Switch.app'"
echo "Install: ./build.sh  (builds, then asks where to install)"
